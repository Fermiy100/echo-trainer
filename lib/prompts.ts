// Все промпты к нейросети — в одном месте, чтобы дорабатывать и тестировать
// отдельно от интерфейса (см. 04-PROJECT-STRUCTURE.md).

// NIM принимает не больше одной картинки за запрос (проверено напрямую: с двумя
// и более — HTTP 400 "At most 1 image(s) may be provided"). Поэтому при
// нескольких фото сначала читаем текст с каждого по отдельности (этот промпт),
// а затем разбираем уже собранный текст одним запросом (buildExplainFromTextPrompt).
export const TRANSCRIBE_PAGE_PROMPT = `Ты — точный сканер текста. Перепиши ВЕСЬ текст с этого фото страницы
учебника дословно, как он написан, ничего не меняя, не поясняя и не сокращая. Сохраняй формулы и
дроби как обычный текст (например, "1/8", "5,1(6)"). Не добавляй ничего от себя — если на фото
не только текст, но и картинка/схема, кратко опиши её одной фразой в скобках. Если текста на фото
вообще нет или он совсем нечитаем, ответь одним словом: ПУСТО.`;

// "unreadable" — обязательное поле-предохранитель против галлюцинаций. Проверено
// напрямую: на нечитаемом/пустом фото модель может уверенно придумать правдоподобный,
// но полностью вымышленный текст параграфа вместо честного признания, что не смогла
// прочитать. Явное требование сначала оценить читаемость снижает такие случаи —
// код проверяет это поле и уходит в честный фоллбэк, если модель его выставила.
const UNREADABLE_INSTRUCTION = `ВАЖНО: сначала оцени, виден ли на фото читаемый текст учебника.
Если фото пустое, слишком тёмное/размытое, или на нём нет текста учебника — поставь
"unreadable": true и оставь остальные поля пустыми/null. НИКОГДА не придумывай
правдоподобный текст параграфа, если не можешь его прочитать на самом деле.`;

// Раньше simplifiedText был короткой "аннотацией о содержании" (3-6 предложений
// в духе "здесь говорится о том-то") — ученик, не читавший оригинал, из такого
// текста не мог понять СУТЬ понятий, только то, что они существуют. Явно требуем
// реально ОБЪЯСНЯТЬ, а не описывать структуру параграфа.
function teachingInstruction(scale: boolean) {
  return `Твоя задача — реально ОБЪЯСНИТЬ материал, а не пересказать, что "здесь говорится о том-то".
Ученик не должен читать оригинал: он должен понять суть каждого понятия из одного твоего текста.
Для каждого термина из keyTerms прямо в simplifiedText скажи, ЧТО ЭТО ТАКОЕ простыми словами —
не просто упомяни термин, а объясни его значение так, будто ученик слышит его впервые.
simplifiedText должен быть ${scale ? "подробным (10-16 предложений, по каждой подтеме отдельно)" : "подробным (8-12 предложений)"} — короткая аннотация не годится.`;
}

// Раньше аналогия принудительно привязывалась к увлечению ученика (футбол, игры
// и т.д.) — на практике это часто выглядело притянутым и нелепым ("представь
// подмножество как офсайд в футболе"). Теперь аналогии всегда универсальные и
// понятные, без искусственной привязки к хобби.
const ANALOGIES_LINE = `"analogies": ["2-3 простые бытовые аналогии из повседневной жизни, каждая объясняет суть ОДНОГО понятия из keyTerms — понятная и естественная, без натянутых сравнений"]`;

const TERM_CARDS_LINE = `"termCards": [{"term": "термин точно как в тексте", "definition": "определение в 1-2 простых предложениях, как будто объясняешь другу, который вообще не в теме — БЕЗ повторения самого термина в определении"}]`;

export function buildExplainSystemPrompt(interest?: string | null) {
  return `Ты — заботливый школьный учитель. Тебе показывают фото страницы учебника.
Прочитай параграф на фото и разбери его для ученика 7 класса. ${UNREADABLE_INSTRUCTION}
${teachingInstruction(false)}
Ответь СТРОГО в формате JSON, без markdown и пояснений вокруг, со следующими полями:
{
  "unreadable": false,
  "subject": "предмет одним-двумя словами, если можно определить по тексту, иначе null",
  "simplifiedText": "подробное объяснение сути, 8-12 предложений — см. инструкцию выше",
  "keyTerms": ["2-5 ключевых терминов из текста, как они звучат в параграфе"],
  ${TERM_CARDS_LINE},
  "keyPoints": ["3-5 ключевых идей параграфа, каждая — одно короткое предложение"],
  ${ANALOGIES_LINE}
}
Верни только этот JSON-объект и ничего больше — ни пояснений до, ни комментариев после.`;
}

export function buildExplainFromTextPrompt(interest?: string | null, pageCount = 1) {
  // Несколько сфотографированных страниц подряд часто содержат НЕСКОЛЬКО разных
  // подтем (например: множества, потом дроби, потом периодические дроби) —
  // если сжать всё в те же короткие лимиты, что и для одной страницы, большая
  // часть материала потеряется. Явно расширяем лимиты по числу фото.
  const scale = pageCount > 1;
  return `Ты — заботливый школьный учитель. Тебе прислали текст, собранный ${
    pageCount > 1 ? `с ${pageCount} сфотографированных подряд страниц учебника` : "с фото страницы учебника"
  } — читай его как один непрерывный текст в том порядке, в каком он идёт.
${
  scale
    ? `Текст может содержать НЕСКОЛЬКО разных подтем подряд (например, сначала одно понятие,
потом другое) — обязательно затронь КАЖДУЮ подтему из текста, не пересказывай только первую.`
    : ""
}
${UNREADABLE_INSTRUCTION}
${teachingInstruction(scale)}
Ответь СТРОГО в формате JSON, без markdown и пояснений вокруг, со следующими полями:
{
  "unreadable": false,
  "subject": "предмет одним-двумя словами, если можно определить по тексту, иначе null",
  "simplifiedText": "${scale ? "подробное объяснение каждой подтемы, 10-16 предложений" : "подробное объяснение сути, 8-12 предложений"} — см. инструкцию выше",
  "keyTerms": ["${scale ? "4-10" : "2-5"} ключевых терминов из текста, как они звучат в оригинале${scale ? " — по всем подтемам, не только по первой" : ""}"],
  ${TERM_CARDS_LINE.replace("{\"term\"", scale ? "// по каждому термину из keyTerms\n  {\"term\"" : "{\"term\"")},
  "keyPoints": ["${scale ? "5-10" : "3-5"} ключевых идей — по каждой подтеме минимум одна, каждая идея одно короткое предложение"],
  ${ANALOGIES_LINE}
}
Верни только этот JSON-объект и ничего больше — ни пояснений до, ни комментариев после.`;
}

export const VERIFY_SYSTEM_PROMPT = `Ты проверяешь устный пересказ ученика против списка ключевых идей параграфа.
Тебе дан список ключевых идей (с индексами от 0) и текст пересказа. Определи, какие идеи
ученик действительно назвал своими словами — пересказ не обязан совпадать дословно, важен смысл.
Ответь СТРОГО в формате JSON: { "coveredIndices": [номера идей, которые ученик назвал] }`;

export function buildVerifyUserPrompt(keyPoints: string[], transcript: string) {
  const list = keyPoints.map((p, i) => `${i}. ${p}`).join("\n");
  return `Ключевые идеи:\n${list}\n\nПересказ ученика:\n"""${transcript}"""`;
}
